// S2: Geliştirme sunucusu + gerçek V20 + YENİ geçici inceleme DB'si. Envanter, aday tablosu, kimlik ve tek kayıtlık karar.
// Her çalıştırma boş DB ile başladığından sayılar her seferinde aynıdır.
const fs = require('fs')
const { scenario } = require('./lib.cjs')
const [BASE, out, workdir] = process.argv.slice(2)
const secret = (name) => fs.readFileSync(`${workdir}/${name}`, 'utf8').trim()

scenario('S2', async ({ browser, check }) => {
  const page = await (await browser.newContext({ viewport: { width: 1280, height: 900 } })).newPage()
  await page.goto(BASE + '/?mod=envanter')
  await page.getByLabel('Dahili erişim anahtarı').fill(secret('token'))
  await page.getByRole('button', { name: 'Oturum aç' }).click()
  const table = page.getByRole('region', { name: /Eser tablosu/ })
  await table.waitFor()
  check('Envanter 10 gerçek eseri listeliyor', (await table.locator('tbody tr').count()) === 10)
  check('10 eserin konumu doğrulanmadı', (await table.getByText('Koordinat doğrulanmadı').count()) === 10)

  const overview = page.getByRole('region', { name: 'Editör inceleme durumu' })
  await overview.getByText(/Açık editoryal sorunlar \(6\)/).waitFor()
  const editorialRow = (await overview.getByRole('row', { name: /Olgunun editör onayı/ }).innerText()).replace(/\s+/g, ' ')
  check('Boş DB: 80 olgu editör kararı bekliyor, 0 onay', /editor 80 0 0 0/.test(editorialRow), editorialRow)
  const identityRow = (await overview.getByRole('row', { name: /Eser kimliği/ }).innerText()).replace(/\s+/g, ' ')
  check('Boş DB: 10 eser kimliği bekliyor', /editor 10 0 0 0/.test(identityRow), identityRow)
  check('Etkin incelemeci hesabı: 1 (yalnızca test hesabı)', await overview.getByText(/etkin incelemeci hesabı: 1/).isVisible())

  await page.getByText(/karşılaştırmalı inceleme tablosu/).click()
  const cand = page.getByRole('region', { name: 'Koordinat adayları karşılaştırması' })
  await cand.waitFor()
  check('Aday tablosu 15 aday gösteriyor', (await cand.locator('tbody tr').count()) === 15)
  check('15 adayın 15i doğrulanmamış', (await cand.getByText('Koordinat doğrulanmadı').count()) === 15)
  const candidateRow = (id) => cand.locator('tbody tr').filter({ has: page.getByRole('cell', { name: id, exact: true }) })
  const cem = (await candidateRow('LC-0008-01').innerText()).replace(/\s+/g, ' ')
  check('Cem Sultan: çelişen aday ve D-0008-01', /çelişen aday.*D-0008-01/.test(cem) && /LC-0008-02: 30\.3 m/.test(cem), cem.slice(0, 160))
  const bed = (await candidateRow('LC-0014-01').innerText()).replace(/\s+/g, ' ')
  check('Bedesten: kullanım alanı, bina izi değil', /Kullanım alanı merkezi/.test(bed) && /bina sınırı değildir/.test(bed))
  check('Güvenli giriş noktası sayısı 0', await page.getByText(/güvenli giriş\s+noktası: 0/).isVisible())
  await cand.screenshot({ path: `${out}/s2-adaylar.png` })

  // Paylaşılan anahtarla karar düğmesi yok.
  await table.getByRole('button', { name: 'Orhan Gazi Türbesi' }).click()
  const panel = page.locator('article.review-panel')
  await panel.getByRole('heading', { name: 'Kaynak ve konum araştırması' }).waitFor()
  check('Kimlik kapısı kapalı', await panel.getByText(/Eser kimliği ve katalog meta verisi yayında: hayır/).isVisible())
  await panel.getByText('Editör, yayın ve oyun kararları').first().click()
  await panel.getByRole('list', { name: 'BUR-0020-F001 kararları' }).waitFor()
  check('Kişisel hesap olmadan "Karar ver" yok', (await panel.getByRole('button', { name: /karar ver/ }).count()) === 0)

  // Kişisel test hesabıyla (geçici DB) tek kayıt.
  const bar = page.getByRole('region', { name: 'İncelemeci kimliği' })
  await bar.getByLabel('İncelemeci hesabı').fill('e2e.editor')
  await bar.getByLabel('Kişisel kimlik bilgisi').fill(secret('reviewer_credential'))
  await bar.getByRole('button', { name: 'İncelemeci olarak giriş yap' }).click()
  await bar.getByText('Tarayıcı Testi Editörü (geçici DB)').waitFor()
  check('Kişisel incelemeci girişi', true)
  await table.getByRole('button', { name: 'Orhan Gazi Türbesi' }).click()
  await page.waitForTimeout(500)
  await panel.getByText('Editör, yayın ve oyun kararları').nth(3).click()
  const f004 = panel.getByRole('list', { name: 'BUR-0020-F004 kararları' })
  await f004.getByRole('button', { name: 'Olgunun editör onayı: karar ver' }).click()
  await panel.getByText(/onay en erken 5 sn sonra/).waitFor()
  await panel.getByLabel('Editör kararı').selectOption('approved')
  await panel.getByLabel('Kaynak kontrolü').selectOption('verified_on_page')
  await panel.getByLabel(/Karar gerekçesi/).fill('Tarayıcı testi: açık sorun varken onay denemesi.')
  check('Süre dolmadan onay düğmesi kapalı', await panel.getByRole('button', { name: 'Kararı kaydet' }).isDisabled())
  await panel.getByRole('button', { name: 'Kararı kaydet' }).and(page.locator(':enabled')).waitFor({ timeout: 8000 })
  await panel.getByRole('button', { name: 'Kararı kaydet' }).click()
  const alert = await panel.getByRole('alert').innerText()
  check('Açık sorunlu olguya onay reddedildi', /issue_unresolved:BUR-0020-ISSUE-001/.test(alert), alert.slice(0, 120))
  check('Yeni bilet açıldı, gerekçe korundu',
        (await panel.getByLabel(/Karar gerekçesi/).inputValue()).startsWith('Tarayıcı testi'))
  await panel.getByLabel('Editör kararı').selectOption('needs_revision')
  await panel.getByLabel(/Karar gerekçesi/).fill('Tarayıcı testi: 1863/1868 çelişkisi çözülene kadar düzeltme gerekli.')
  await panel.getByRole('button', { name: 'Kararı kaydet' }).and(page.locator(':enabled')).waitFor()
  await panel.getByRole('button', { name: 'Kararı kaydet' }).click()
  await f004.getByText('Düzeltme gerekli', { exact: true }).waitFor()
  check('Düzeltme kararı kaydedildi ve panelde görünüyor', true)
  await page.screenshot({ path: `${out}/s2-karar.png`, fullPage: false })
})
