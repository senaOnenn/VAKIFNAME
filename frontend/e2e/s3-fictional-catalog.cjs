// S3: Kurgusal (BUR-9xxx) onaylı katalog. Yalnızca kimliği onaylı eser de listelenir; konumsuz eser haritada yok.
const { scenario } = require('./lib.cjs')
const [BASE, out] = process.argv.slice(2)

scenario('S3', async ({ browser, check }) => {
  const page = await (await browser.newContext({ viewport: { width: 1280, height: 900 } })).newPage()
  await page.goto(BASE + '/')
  const list = page.getByRole('list', { name: 'Gerçek eser listesi' })
  await list.waitFor()
  check('Onaylı 2 eser listeleniyor (biri yalnızca kimlik)', (await list.getByRole('article').count()) === 2)
  check('Konumsuz eser kartında uyarı', await list.getByText(/Konum henüz haritada gösterilmiyor/).isVisible())
  await page.locator('.leaflet-marker-icon').first().waitFor()
  check('Haritada yalnızca 1 işaret', (await page.locator('.leaflet-marker-icon').count()) === 1)
  await page.getByRole('button', { name: 'Ayrıntıları gör: Test Eseri BUR-9001' }).click()
  const panel = page.getByRole('complementary', { name: 'Eser ayrıntıları' })
  await panel.getByText('Kaynaklı bilgiler').waitFor()
  const text = await panel.innerText()
  check('Yalnızca onaylı olgu (F001)', text.includes('KURGUSAL OLGU BUR-9001-F001') && !text.includes('BUR-9001-F002'))
  check('Check-in kapalı mesajı', text.includes('konum tabanlı görev açılmadı'))
  check('Araştırma erişim notu sızmıyor', !text.includes('Test notu.'))
  check('Alıntı/gerekçe sızmıyor', !text.includes('KURGUSAL ALINTI') && !text.includes('Kaynak sayfası okundu'))
  await page.screenshot({ path: `${out}/s3-katalog.png`, fullPage: true })
})
